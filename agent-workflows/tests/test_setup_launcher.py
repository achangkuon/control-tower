import os
from pathlib import Path
import stat
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "tools/setup.sh"
MARKER = "# Generated by agent-workflows/tools/setup.sh — do not edit."


def launcher(repo=ROOT):
    return f'#!/usr/bin/env bash\n{MARKER}\nexec "{repo}/tools/setup.sh" "$@"\n'.encode()


class SetupLauncherTests(unittest.TestCase):
    def setUp(self):
        self.tempdir = tempfile.TemporaryDirectory()
        self.addCleanup(self.tempdir.cleanup)
        self.home = Path(self.tempdir.name)
        self.bin = self.home / ".local/bin"
        self.bin.mkdir(parents=True)
        self.target = self.bin / "torre-setup"
        self.tower = self.bin / "torre-control"
        self.tower_bytes = b"#!/bin/sh\n# Tower V1 sentinel\nexit 42\n"
        self.tower.write_bytes(self.tower_bytes)
        self.tower.chmod(0o751)
        self.env = {
            "HOME": str(self.home), "SETUP_HOME": str(self.home),
            "SETUP_BIN_DIR": str(self.bin), "PATH": os.defpath,
            "PYTHONDONTWRITEBYTECODE": "1",
        }

    def run_setup(self, flag="--link", name=None, install=False):
        env = dict(self.env)
        if name is not None:
            env["SETUP_LAUNCHER"] = name
        if install:
            (self.home / ".claude").mkdir()
            # Exercise the real skills installer, but never pull or use real agents.
            command = ["bash", "-c", 'source "$1"; pull_repo() { :; }; run_install',
                       "setup-test", str(SCRIPT)]
        else:
            command = ["bash", str(SCRIPT), flag]
        return subprocess.run(command, env=env, capture_output=True, text=True, timeout=20)

    def assert_tower_unchanged(self):
        self.assertEqual(self.tower.read_bytes(), self.tower_bytes)
        self.assertEqual(stat.S_IMODE(self.tower.stat().st_mode), 0o751)

    def test_link_creates_default_with_exact_bytes_and_mode(self):
        result = self.run_setup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(self.target.exists(), result.stdout)
        self.assertEqual(self.target.read_bytes(), launcher())
        self.assertEqual(stat.S_IMODE(self.target.stat().st_mode), 0o755)
        self.assert_tower_unchanged()

    def test_link_updates_exact_generated_launcher_from_old_checkout(self):
        self.target.write_bytes(launcher("/old checkout/agent-workflows"))
        result = self.run_setup(name="torre-setup")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.target.read_bytes(), launcher())
        self.assert_tower_unchanged()

    def test_link_preserves_foreign_launcher(self):
        contents = (b"#!/bin/sh\necho personal\n", launcher() + b"# extra\n",
                    launcher().rstrip(b"\n"), launcher().replace(b'"$@"', b'"$*"'))
        for content in contents:
            with self.subTest(content=content):
                self.target.write_bytes(content)
                self.target.chmod(0o640)
                result = self.run_setup(name="torre-setup")
                self.assertNotEqual(result.returncode, 0)
                self.assertIn("no se modifica", result.stdout + result.stderr)
                self.assertEqual(self.target.read_bytes(), content)
                self.assertEqual(stat.S_IMODE(self.target.stat().st_mode), 0o640)
        self.assert_tower_unchanged()

    def test_link_preserves_symlink_to_tower(self):
        self.target.symlink_to(self.tower)
        result = self.run_setup(name="torre-setup")
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(self.target.is_symlink())
        self.assert_tower_unchanged()

    def test_reserved_name_refused_preserving_existing_tower(self):
        result = self.run_setup(name="torre-control")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Torre V1", result.stdout + result.stderr)
        self.assertIn("torre-setup", result.stdout + result.stderr)
        self.assert_tower_unchanged()

    def test_reserved_basename_refused_even_with_path_prefix(self):
        result = self.run_setup(name="./torre-control")
        self.assertNotEqual(result.returncode, 0)
        self.assert_tower_unchanged()

    def test_reserved_name_never_created(self):
        other_bin = self.home / "empty-bin"
        self.env["SETUP_BIN_DIR"] = str(other_bin)
        result = self.run_setup(name="torre-control")
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse((other_bin / "torre-control").exists())
        self.assert_tower_unchanged()

    def test_install_default_preserves_tower_and_creates_setup(self):
        result = self.run_setup(install=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(self.target.read_bytes(), launcher())
        self.assert_tower_unchanged()

    def test_install_succeeds_when_reserved_launcher_refused(self):
        result = self.run_setup(name="torre-control", install=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("Torre V1", result.stdout + result.stderr)
        self.assertIn("skills instaladas", result.stdout)
        self.assertTrue((self.home / ".agents/skills/chanks-1-prd/SKILL.md").is_file())
        self.assert_tower_unchanged()

    def test_install_succeeds_with_foreign_setup_and_preserves_it(self):
        foreign = b"personal setup\n"
        self.target.write_bytes(foreign)
        result = self.run_setup(install=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("skills instaladas", result.stdout)
        self.assertEqual(self.target.read_bytes(), foreign)
        self.assert_tower_unchanged()

    def test_help_names_installer_not_tower(self):
        result = self.run_setup(flag="--help")
        self.assertEqual(result.returncode, 0)
        self.assertIn("`torre-setup`", result.stdout)
        self.assertNotIn("`torre-control`", result.stdout)


if __name__ == "__main__":
    unittest.main()
