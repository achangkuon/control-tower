import { afterEach, beforeEach, describe, expect, test, spyOn } from "bun:test";
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import { dirname, join } from "node:path";
import { BUNDLE_MEMBERS } from "../bundle.mjs";
import { installGlobal, updateGlobal, doctorGlobal, rollbackGlobal } from "../global.mjs";

const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const paths = [...BUNDLE_MEMBERS.map(({ source }) => source), ...[
  "adoption", "bundle", "project-files", "bootstrap", "release", "global", "projects", "cli",
].map((name) => `product/tower/v1/${name}.mjs`)];
const environmentKeys = ["HOME", "XDG_DATA_HOME", "XDG_CONFIG_HOME", "XDG_CACHE_HOME",
  "GIT_CONFIG_GLOBAL", "GIT_CONFIG_SYSTEM", "GH_CONFIG_DIR"];
let root, options, environment;
const legacyBytes = (repo) => Buffer.from('#!/usr/bin/env bash\n' +
  '# Generated by agent-workflows/tools/setup.sh — do not edit.\n' +
  `exec "${repo}/tools/setup.sh" "$@"\n`);
const statePath = () => join(options.stateRoot, "state.json");
const state = () => JSON.parse(fs.readFileSync(statePath(), "utf8"));
const version = (id) => join(options.stateRoot, "versions", id);

function acquisition(label = "a", overrides = {}, runtime = false) {
  const members = paths.map((path) => {
    // Opaque fixtures are never executed; relocation scenarios opt in to real runtime modules.
    const bytes = runtime && path.endsWith(".mjs") ?
      fs.readFileSync(new URL(`../../../../${path}`, import.meta.url)) :
      Buffer.from(`opaque fixture ${label}: ${path}\n`);
    return { path, type: "file", encoding: "base64", byteLength: bytes.length,
      sha256: hash(bytes), bytes: bytes.toString("base64") };
  });
  const wire = Buffer.from(JSON.stringify({ schema: "tower.v1.release/1", members }));
  const calls = [];
  const acquire = { repository: "example/control-tower", tag: `v1-${label}`, asset: "tower.json",
    sha256: hash(wire), runner: (command, argv) => {
      calls.push([command, argv]);
      return { status: 0, stdout: argv[0] === "auth" ? Buffer.alloc(0) : wire };
    }, ...overrides };
  return { acquire, wire, calls, id: hash(wire) };
}
function install(label = "a", extra = {}) {
  const release = acquisition(label);
  installGlobal({ ...options, acquire: release.acquire, ...extra });
  return release;
}
function snapshot(path = root) {
  const stat = fs.lstatSync(path);
  if (stat.isSymbolicLink()) return { link: fs.readlinkSync(path) };
  if (stat.isDirectory()) return { mode: stat.mode & 0o7777,
    children: Object.fromEntries(fs.readdirSync(path).sort().map((name) => [name, snapshot(join(path, name))])) };
  return { mode: stat.mode & 0o7777, bytes: fs.readFileSync(path).toString("base64") };
}
function rewrite(path, value) {
  fs.chmodSync(path, 0o600);
  fs.writeFileSync(path, typeof value === "string" || Buffer.isBuffer(value) ? value : JSON.stringify(value));
}
function failure(boundary) {
  return (step) => { if (step === boundary) throw new Error(`injected ${step}`); };
}

beforeEach(() => {
  root = fs.mkdtempSync(join(fs.realpathSync("/tmp"), "tower-global-test-"));
  environment = Object.fromEntries(environmentKeys.map((key) => [key, process.env[key]]));
  for (const key of environmentKeys) process.env[key] = join(root, key);
  fs.mkdirSync(join(root, "bin"));
  options = { stateRoot: join(root, "v1"), launcherPath: join(root, "bin", "torre-control"),
    knownLegacyRepository: join(root, "independent", "agent-workflows") };
  // Project-local and legacy-engine records are unrelated and never become authority.
  fs.mkdirSync(join(root, "project"));
  fs.writeFileSync(join(root, "project", ".control-tower-adoption-v1"), "local journal sentinel");
  fs.writeFileSync(join(root, "active.json"), "legacy engine sentinel");
});
afterEach(() => {
  for (const key of environmentKeys) {
    if (environment[key] === undefined) delete process.env[key]; else process.env[key] = environment[key];
  }
  fs.rmSync(root, { recursive: true, force: true }); // Only this test's disposable root.
});

describe("isolated global V1 lifecycle", () => {
  test("fresh installation stores 72 verified files and a stable non-eval launcher", () => {
    const release = install();
    expect(release.calls.length).toBe(2);
    expect(state().active).toBe(release.id);
    expect(state().previous).toBeNull();
    for (const path of paths) expect(fs.readFileSync(join(version(release.id), path), "utf8"))
      .toBe(`opaque fixture a: ${path}\n`);
    const launcher = fs.readFileSync(options.launcherPath, "utf8");
    expect(launcher.startsWith("#!/usr/bin/env bun\n")).toBe(true);
    expect(launcher).toContain("state.json");
    expect(launcher).toContain("cli.mjs");
    expect(launcher).not.toMatch(/eval\(|exec\(|spawn\(|setup\.sh/);
    expect(fs.statSync(options.launcherPath).mode & 0o7777).toBe(0o755);
    expect(doctorGlobal(options).status).toBe("healthy");
    rollbackGlobal(options);
    expect(fs.existsSync(options.launcherPath)).toBe(false);
    expect(fs.existsSync(statePath())).toBe(false);
    expect(doctorGlobal(options).status).toBe("absent");
    expect(fs.readFileSync(join(root, "active.json"), "utf8")).toBe("legacy engine sentinel");
    expect(fs.readFileSync(join(root, "project", ".control-tower-adoption-v1"), "utf8"))
      .toBe("local journal sentinel");
  });

  test("exact three-line legacy migration preserves arbitrary original mode and restores bytes", () => {
    const bytes = legacyBytes(options.knownLegacyRepository);
    fs.writeFileSync(options.launcherPath, bytes, { mode: 0o751 });
    install();
    expect(state().original.bytes).toBe(bytes.toString("base64"));
    expect(state().original.mode).toBe(0o751);
    rollbackGlobal(options);
    expect(fs.readFileSync(options.launcherPath)).toEqual(bytes);
    expect(fs.statSync(options.launcherPath).mode & 0o7777).toBe(0o751);
  });

  for (const changedUpdate of [false, true]) {
    test(`checkout migration survives installed CLI relocation (changed update=${changedUpdate})`, async () => {
      const checkout = join(root, "checkout");
      const moduleRoot = join(checkout, "product", "tower", "v1");
      fs.mkdirSync(moduleRoot, { recursive: true });
      for (const path of paths.filter((path) => path.endsWith(".mjs"))) {
        fs.mkdirSync(dirname(join(checkout, path)), { recursive: true });
        fs.copyFileSync(new URL(`../../../../${path}`, import.meta.url), join(checkout, path));
      }
      const checkoutAPI = await import(join(moduleRoot, "global.mjs"));
      const { knownLegacyRepository: _ignored, ...relocatedOptions } = options;
      const bytes = legacyBytes(join(checkout, "agent-workflows"));
      fs.writeFileSync(options.launcherPath, bytes);
      fs.chmodSync(options.launcherPath, 0o751);
      const pin = { repository: "achangkuon/control-tower" };
      const first = acquisition("runtime-a", pin, true);
      checkoutAPI.installGlobal({ ...relocatedOptions, acquire: first.acquire });
      // This is the exact v1.0.0 original() record, with no new metadata fields.
      expect(state().original).toEqual({ kind: "legacy", mode: 0o751,
        bytes: bytes.toString("base64"), sha256: hash(bytes) });
      const installedRoot = join(version(first.id), "product", "tower", "v1");
      const installedAPI = await import(join(installedRoot, "global.mjs"));
      const { main } = await import(join(installedRoot, "cli.mjs"));
      const invoke = (argv, runner) => {
        let stdout = "", stderr = "";
        const code = main([...argv, "--state", options.stateRoot, "--launcher", options.launcherPath], {
          env: process.env, runner, stdout: { write: (text) => { stdout += text; } },
          stderr: { write: (text) => { stderr += text; } },
        });
        expect(stderr).toBe("");
        expect(code).toBe(0);
        return JSON.parse(stdout);
      };
      expect(installedAPI.doctorGlobal(relocatedOptions)).toEqual(checkoutAPI.doctorGlobal(relocatedOptions));
      expect(invoke(["doctor"]).status).toBe("healthy");
      const next = changedUpdate ? acquisition("runtime-b", pin, true) : first;
      const updated = invoke(["update", "--tag", next.acquire.tag, "--asset", next.acquire.asset,
        "--sha256", next.id], next.acquire.runner);
      expect(updated.status).toBe(changedUpdate ? "activated" : "unchanged");
      expect(invoke(["doctor"]).active).toBe(next.id);
      const rolled = invoke(["rollback"]);
      if (changedUpdate) {
        expect(rolled.active).toBe(first.id);
        expect(installedAPI.doctorGlobal(relocatedOptions)).toEqual(checkoutAPI.doctorGlobal(relocatedOptions));
      } else {
        expect(rolled.status).toBe("restored");
        expect(fs.readFileSync(options.launcherPath)).toEqual(bytes);
        expect(fs.statSync(options.launcherPath).mode & 0o7777).toBe(0o751);
      }
    });
  }

  test("retained backup rejects altered evidence and noncanonical generated shapes without mutation", () => {
    const bytes = legacyBytes(options.knownLegacyRepository);
    fs.writeFileSync(options.launcherPath, bytes);
    install();
    const saved = state();
    const forged = (bytes) => ({ ...saved.original, bytes: bytes.toString("base64"), sha256: hash(bytes) });
    const invalid = [
      { ...saved.original, sha256: "0".repeat(64) },
      { ...saved.original, bytes: saved.original.bytes + "\n" },
      ...[-1, 0o10000, 1.5, "755"].map((mode) => ({ ...saved.original, mode })),
      forged(Buffer.concat([bytes, Buffer.from("# extra\n")])),
      forged(Buffer.concat([bytes, Buffer.from("\n")])),
      forged(Buffer.from(bytes.toString().replace("Generated by", "Written by"))),
      forged(bytes.subarray(0, -1)),
      ...["relative", "/tmp/../foreign", "/", '/tmp/"foreign', "/tmp/`foreign", "/tmp/$foreign",
        "/tmp/\\foreign"].map((path) => forged(legacyBytes(path))),
    ];
    for (const original of invalid) {
      rewrite(statePath(), { ...saved, original });
      const before = snapshot();
      const next = acquisition("b");
      for (const run of [() => doctorGlobal(options), () => rollbackGlobal(options),
        () => updateGlobal({ ...options, acquire: next.acquire })]) expect(run).toThrow(/retained launcher backup/);
      expect(next.calls).toEqual([]);
      expect(snapshot()).toEqual(before);
    }
  });

  test("update uses one state record, preserves launcher and reuses immutable versions", () => {
    const first = install();
    const launcher = snapshot(options.launcherPath);
    const second = acquisition("b");
    updateGlobal({ ...options, acquire: second.acquire });
    expect(state().active).toBe(second.id);
    expect(state().previous).toBe(first.id);
    expect(snapshot(options.launcherPath)).toEqual(launcher);
    const before = snapshot();
    expect(updateGlobal({ ...options, acquire: second.acquire }).status).toBe("unchanged");
    expect(snapshot()).toEqual(before);
    rollbackGlobal(options);
    expect(state().active).toBe(first.id);
    expect(state().previous).toBe(second.id);
    updateGlobal({ ...options, acquire: second.acquire });
    expect(fs.readdirSync(join(options.stateRoot, "versions")).sort()).toEqual([first.id, second.id].sort());
  });

  test("doctor is read-only, performs no download and refuses inactive previous-version drift", () => {
    const first = install();
    updateGlobal({ ...options, acquire: acquisition("b").acquire });
    const before = snapshot();
    expect(doctorGlobal(options).status).toBe("healthy");
    expect(snapshot()).toEqual(before);
    const memberPath = join(version(first.id), paths[0]);
    const changed = fs.readFileSync(memberPath);
    changed[0] ^= 1; // Same length: content integrity, not merely the size bound.
    rewrite(memberPath, changed);
    fs.chmodSync(memberPath, 0o400);
    for (const run of [() => doctorGlobal(options), () => rollbackGlobal(options),
      () => updateGlobal({ ...options, acquire: acquisition("c").acquire })]) expect(run).toThrow();
  });

  test("acquisition is pinned before mutation and runner mutation cannot change stored provenance", () => {
    const bad = acquisition("a", { sha256: "0".repeat(64) });
    const before = snapshot();
    expect(() => installGlobal({ ...options, acquire: bad.acquire })).toThrow(/SHA-256/);
    expect(snapshot()).toEqual(before);
    const good = acquisition();
    const originalRunner = good.acquire.runner;
    good.acquire.runner = (...args) => {
      good.acquire.repository = "foreign/repository";
      good.acquire.sha256 = "0".repeat(64);
      return originalRunner(...args);
    };
    installGlobal({ ...options, acquire: good.acquire });
    const provenance = JSON.parse(fs.readFileSync(join(version(good.id), "provenance.json"), "utf8"));
    expect(provenance.repository).toBe("example/control-tower");
    expect(provenance.sha256).toBe(good.id);
  });

  test("unknown launchers and blocking types are preserved without any mutation", () => {
    for (const bytes of [Buffer.from("foreign\n"), legacyBytes("/foreign/agent-workflows"),
      Buffer.concat([legacyBytes(options.knownLegacyRepository), Buffer.from("# extra\n")]),
      legacyBytes(options.knownLegacyRepository).subarray(0, -1)]) {
      fs.writeFileSync(options.launcherPath, bytes);
      const before = snapshot();
      expect(() => install()).toThrow();
      expect(snapshot()).toEqual(before);
    }
    fs.unlinkSync(options.launcherPath);
    fs.symlinkSync(join(root, "active.json"), options.launcherPath);
    const linked = snapshot();
    expect(() => install()).toThrow();
    expect(snapshot()).toEqual(linked);
    fs.unlinkSync(options.launcherPath);
    fs.linkSync(join(root, "active.json"), options.launcherPath);
    const hardlinked = snapshot();
    expect(() => install()).toThrow();
    expect(snapshot()).toEqual(hardlinked);
    fs.unlinkSync(options.launcherPath);
    fs.mkdirSync(options.launcherPath);
    const directory = snapshot();
    expect(() => install()).toThrow();
    expect(snapshot()).toEqual(directory);
  });

  test("invalid options, aliased roots and unsafe ancestors fail closed", () => {
    fs.symlinkSync(join(root, "bin"), join(root, "alias"));
    const before = snapshot();
    for (const changes of [{ stateRoot: "relative" }, { stateRoot: root + "/v1/../v1" },
      { launcherPath: join(root, "alias", "torre-control") }, { launcherPath: join(options.stateRoot, "command") },
      { knownLegacyRepository: '/unsafe/"$(echo nope)' }, { extra: true }, { fault: true }]) {
      expect(() => installGlobal({ ...options, ...changes, acquire: acquisition().acquire })).toThrow();
    }
    const accessor = { ...options, acquire: acquisition().acquire };
    Object.defineProperty(accessor, "stateRoot", { get: () => { throw new Error("getter executed"); } });
    expect(() => installGlobal(accessor)).toThrow(/options/i);
    expect(snapshot()).toEqual(before);
  });

  test("malformed state, provenance, missing/extra members, pointers and retained backups are rejected", () => {
    const release = install();
    const originalState = fs.readFileSync(statePath());
    for (const change of [{ schema: "unknown" }, { active: "../foreign" }, { previous: "f".repeat(64) },
      { active: "f".repeat(64) },
      { original: { kind: "legacy", bytes: "Zm9yZWlnbg==", mode: 0o755, sha256: hash("foreign") } }, { extra: true }]) {
      rewrite(statePath(), { ...JSON.parse(originalState), ...change });
      expect(() => doctorGlobal(options)).toThrow();
      rewrite(statePath(), originalState);
    }
    rewrite(statePath(), '{"schema":"ignored","schema":"tower.v1.global/1"}');
    expect(() => doctorGlobal(options)).toThrow();
    rewrite(statePath(), originalState);
    const provenancePath = join(version(release.id), "provenance.json");
    const provenance = fs.readFileSync(provenancePath);
    rewrite(provenancePath, { ...JSON.parse(provenance), repository: "bad" });
    expect(() => doctorGlobal(options)).toThrow();
    rewrite(provenancePath, provenance);
    fs.chmodSync(provenancePath, 0o400);
    const member = join(version(release.id), paths[0]);
    const bytes = fs.readFileSync(member);
    fs.unlinkSync(member);
    expect(() => doctorGlobal(options)).toThrow();
    fs.writeFileSync(member, bytes, { mode: 0o400 });
    fs.writeFileSync(join(version(release.id), "extra"), "foreign");
    const before = snapshot();
    expect(() => rollbackGlobal(options)).toThrow();
    expect(snapshot()).toEqual(before);
  });

  test("store conflicts, stale locks and recovery evidence are never reclaimed", () => {
    install();
    for (const name of ["foreign", ".transaction", ".lock"]) {
      const path = join(options.stateRoot, name);
      fs.writeFileSync(path, "foreign");
      const before = snapshot();
      expect(() => updateGlobal({ ...options, acquire: acquisition("b").acquire })).toThrow();
      expect(() => doctorGlobal(options)).toThrow();
      expect(snapshot()).toEqual(before);
      fs.unlinkSync(path);
    }
    const next = acquisition("b");
    fs.mkdirSync(version(next.id));
    const before = snapshot();
    expect(() => updateGlobal({ ...options, acquire: next.acquire })).toThrow();
    expect(snapshot()).toEqual(before);
  });

  test("bounded reads reject huge records before allocating or reading their contents", () => {
    install();
    const fd = fs.openSync(statePath(), "w");
    fs.ftruncateSync(fd, 32 * 1024 * 1024);
    fs.closeSync(fd);
    const open = spyOn(fs, "openSync");
    try {
      expect(() => doctorGlobal(options)).toThrow(/bound|size/i);
      // Other bounded version files may be read; the oversized state must never be opened.
      expect(open.mock.calls.some(([path]) => path === statePath())).toBe(false);
    } finally { open.mockRestore(); }
  });

  for (const boundary of ["locked", "journal", "stage", "publish", "published", "activation", "state-active", "launcher", "readback", "finish"]) {
    test(`first installation compensates at ${boundary} without changing original bytes/mode`, () => {
      fs.writeFileSync(options.launcherPath, legacyBytes(options.knownLegacyRepository), { mode: 0o711 });
      const before = snapshot();
      expect(() => install("a", { fault: failure(boundary) })).toThrow(`injected ${boundary}`);
      expect(snapshot()).toEqual(before);
    });
  }
  for (const boundary of ["stage", "published", "activation", "state-active", "readback", "finish"]) {
    test(`failed update at ${boundary} leaves prior payload and state intact`, () => {
      install();
      const before = snapshot();
      expect(() => updateGlobal({ ...options, acquire: acquisition("b").acquire, fault: failure(boundary) }))
        .toThrow(`injected ${boundary}`);
      expect(snapshot()).toEqual(before);
      expect(doctorGlobal(options).status).toBe("healthy");
    });
  }

  for (const previous of [false, true]) {
    for (const boundary of ["activation", "readback", "finish"]) {
      test(`rollback with previous=${previous} compensates at ${boundary}`, () => {
        install();
        if (previous) updateGlobal({ ...options, acquire: acquisition("b").acquire });
        const before = snapshot();
        expect(() => rollbackGlobal({ ...options, fault: failure(boundary) })).toThrow(`injected ${boundary}`);
        expect(snapshot()).toEqual(before);
        expect(doctorGlobal(options).status).toBe("healthy");
      });
    }
  }

  test("failed fresh install restores absence, including transaction containers", () => {
    const before = snapshot();
    expect(() => install("a", { fault: failure("readback") })).toThrow("injected readback");
    expect(snapshot()).toEqual(before);
  });

  test("a syntactically valid substituted provenance still conflicts with the activated pin", () => {
    const release = install();
    const path = join(version(release.id), "provenance.json");
    rewrite(path, { ...JSON.parse(fs.readFileSync(path)), repository: "foreign/repository" });
    fs.chmodSync(path, 0o400);
    const before = snapshot();
    expect(() => doctorGlobal(options)).toThrow(/provenance/i);
    expect(snapshot()).toEqual(before);
  });

  test("stored hardlinks and symlinks are rejected without modifying their targets", () => {
    const release = install();
    const member = join(version(release.id), paths[0]);
    const saved = fs.readFileSync(member);
    for (const kind of ["hardlink", "symlink"]) {
      fs.unlinkSync(member);
      if (kind === "hardlink") fs.linkSync(join(root, "active.json"), member);
      else fs.symlinkSync(join(root, "active.json"), member);
      const before = snapshot();
      expect(() => doctorGlobal(options)).toThrow();
      expect(snapshot()).toEqual(before);
      fs.unlinkSync(member);
      fs.writeFileSync(member, saved, { mode: 0o400 });
    }
  });

  test("launcher ownership lock also excludes a different state namespace", () => {
    fs.writeFileSync(options.launcherPath + ".tower-v1-lock", "foreign owner");
    const before = snapshot();
    expect(() => installGlobal({ ...options, stateRoot: join(root, "other-v1"), acquire: acquisition().acquire })).toThrow();
    expect(snapshot()).toEqual(before);
  });

  test("foreign stage artifacts survive a failed ownership preflight", () => {
    let error;
    try { install("a", { fault: (step, context) => {
      if (step !== "stage") return;
      fs.writeFileSync(join(context.transactionPath, "version", "foreign"), "foreign artifact");
      throw new Error("injected stage");
    } }); } catch (caught) { error = caught; }
    expect(error).toBeInstanceOf(AggregateError);
    expect(fs.readFileSync(join(options.stateRoot, ".transaction", "version", "foreign"), "utf8"))
      .toBe("foreign artifact");
  });

  for (const destination of ["provenance.json", "state.json", "torre-control"]) {
    test(`actual filesystem failure writing/publishing ${destination} compensates`, () => {
      const before = snapshot();
      const method = destination === "provenance.json" ? "writeFileSync" : "renameSync";
      const original = fs[method];
      let injected = false;
      const call = spyOn(fs, method).mockImplementation((...args) => {
        const target = method === "renameSync" ? args[1] : args[0];
        if (!injected && target.endsWith("/" + destination)) {
          injected = true;
          throw new Error("injected filesystem failure");
        }
        return original(...args);
      });
      try { expect(() => install()).toThrow("injected filesystem failure"); }
      finally { call.mockRestore(); }
      expect(injected).toBe(true);
      expect(snapshot()).toEqual(before);
    });
  }

  test("failed legacy restoration compensates back to the installed state", () => {
    fs.writeFileSync(options.launcherPath, legacyBytes(options.knownLegacyRepository), { mode: 0o705 });
    install();
    const before = snapshot();
    expect(() => rollbackGlobal({ ...options, fault: failure("readback") })).toThrow("injected readback");
    expect(snapshot()).toEqual(before);
  });

  test("foreign publication destination is preserved with recovery evidence", () => {
    const release = acquisition();
    expect(() => installGlobal({ ...options, acquire: release.acquire, fault: (step) => {
      if (step === "publish") fs.mkdirSync(version(release.id));
    } })).toThrow(AggregateError);
    expect(fs.readdirSync(version(release.id))).toEqual([]);
    expect(fs.existsSync(join(options.stateRoot, ".transaction", "recovery.json"))).toBe(true);
  });

  test("overlapping mutation cannot acquire ownership of the same lifecycle", () => {
    install("a", { fault: (step) => {
      if (step !== "stage") return;
      const before = snapshot();
      expect(() => installGlobal({ ...options, acquire: acquisition("b").acquire })).toThrow();
      expect(snapshot()).toEqual(before);
    } });
    expect(doctorGlobal(options).status).toBe("healthy");
  });

  test("failed compensation reports both errors and retains bounded owned recovery evidence", () => {
    let error;
    try { install("a", { fault: (step) => {
      if (["readback", "compensation"].includes(step)) throw new Error(`injected ${step}`);
    } }); } catch (caught) { error = caught; }
    expect(error).toBeInstanceOf(AggregateError);
    expect(error.errors.map(({ message }) => message)).toEqual(["injected readback", "injected compensation"]);
    const journal = join(options.stateRoot, ".transaction", "recovery.json");
    expect(fs.statSync(journal).size).toBeLessThan(64 * 1024);
    expect(JSON.parse(fs.readFileSync(journal, "utf8")).operation).toBe("install");
    const before = snapshot();
    expect(() => rollbackGlobal(options)).toThrow();
    expect(snapshot()).toEqual(before);
  });

  test("compensation refuses foreign replacement instead of overwriting it", () => {
    let error;
    try { install("a", { fault: (step) => {
      if (step !== "readback") return;
      fs.unlinkSync(options.launcherPath);
      fs.writeFileSync(options.launcherPath, "foreign replacement\n");
      throw new Error("injected readback");
    } }); } catch (caught) { error = caught; }
    expect(error).toBeInstanceOf(AggregateError);
    expect(fs.readFileSync(options.launcherPath, "utf8")).toBe("foreign replacement\n");
    expect(fs.existsSync(join(options.stateRoot, ".transaction", "recovery.json"))).toBe(true);
  });
});
